// 배포 빌드 전에 안내문(처리방침·동의문) 본문에 자리표시가 남았는지 본다. 하나라도 있으면 실패한다.
// 자리표시는 대괄호로 싼 한글로 시작하는 토큰이다(예: [보호책임자 실명], [시행일]). 코드의 배열·타입 대괄호는 한글로 시작하지 않는다.
// ponytail: 한글로 시작하는 자리표시만 본다. 영문 자리표시([TBD] 같은)를 쓰게 되면 규칙을 넓힌다.
export const findPlaceholders = (src: string): string[] => src.match(/\[[가-힣][^\]\n]*\]/g) ?? []
